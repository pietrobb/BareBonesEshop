// A clone contains tracked files only: no config.php, no cache/db/logs dirs, jobs/storage/uploads
// only as .gitkeep placeholders. vendor/bbf is the submodule.
$a111Copy = static function (string $from, string $to, string $relative = '') use (&$a111Copy): void {
    $skip = ['.git', 'node_modules', 'releases', 'tests', 'docs', 'demo', 'parity-report', 'playwright-report',
        'test-results', '.lighthouseci', 'config.php', 'admin-roles.json', '.env', 'cache', 'db', 'logs'];
    $placeholdersOnly = ['jobs', 'storage', 'uploads'];
    if (!is_dir($to)) mkdir($to, 0777, true);
    foreach (scandir($from) ?: [] as $entry) {
        if ($entry === '.' || $entry === '..') continue;
        $top = explode('/', $relative . $entry)[0];
        if ($relative === '' && in_array($entry, $skip, true)) continue;
        if ($relative === 'import/' && str_starts_with($entry, 'template-')) continue; // generated by schema-build
        $path = $from . '/' . $entry;
        if (is_dir($path)) {
            $a111Copy($path, $to . '/' . $entry, $relative . $entry . '/');
        } elseif (!in_array($top, $placeholdersOnly, true) || $entry === '.gitkeep') {
            copy($path, $to . '/' . $entry);
        }
    }
};
$a111RemoveTree = static function (string $path): void {
    if (!is_dir($path)) { @unlink($path); return; }
    foreach (new RecursiveIteratorIterator(new RecursiveDirectoryIterator($path, FilesystemIterator::SKIP_DOTS), RecursiveIteratorIterator::CHILD_FIRST) as $item) {
        $item->isDir() ? @rmdir($item->getPathname()) : @unlink($item->getPathname());
    }
    @rmdir($path);
};
$a111Env = getenv();
