$a111Php = static function (array $args, array $extraEnv = []) use ($a111Shop, $a111Base, $a111Env): array {
    $errFile = $a111Base . '/stderr-' . bin2hex(random_bytes(4)) . '.log';
    $process = proc_open(array_merge([PHP_BINARY], $args), [0 => ['pipe', 'r'], 1 => ['pipe', 'w'], 2 => ['file', $errFile, 'w']], $pipes, $a111Shop, $extraEnv + $a111Env);
    fclose($pipes[0]);
    $out = (string)stream_get_contents($pipes[1]);
    fclose($pipes[1]);
    $code = proc_close($process);
    $err = (string)@file_get_contents($errFile);
    @unlink($errFile);
    return ['code' => $code, 'out' => $out, 'err' => $err];
};

